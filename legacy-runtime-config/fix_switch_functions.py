"""Derives `functions = [{address, size}, ...]` overrides for functions whose jump-table cases
land past the end of the function XenonRecomp believed in.

XenonRecomp reports these as
    ERROR: Switch case at <bctr address> is trying to jump outside function: <target>
and then emits `return;` for the case, which silently breaks the function. The fix is to tell the
recompiler how long the function really is.

The overrides only ever EXTEND a function relative to the extent the recompiler actually used
(Q4_DUMP_FUNCTIONS output), because the error can be reported for a small inner function that
sits inside a bigger one.

Usage: python -I fix_switch_functions.py <recomp.out.log> <image.bin> <functions_dump.txt> <out.toml>
"""
import bisect
import re
import struct
import sys

log_path, image_path, dump_path, out_path = sys.argv[1:5]
prev_path = sys.argv[5] if len(sys.argv) > 5 else None

IMAGE_BASE = 0x82000000
image = open(image_path, "rb").read()


def word(addr):
    off = addr - IMAGE_BASE
    return struct.unpack(">I", image[off:off + 4])[0]


# Functions exactly as the recompiler saw them: (base, size), possibly overlapping.
functions = []
for line in open(dump_path):
    parts = line.split()
    if len(parts) == 2:
        functions.append((int(parts[0], 16), int(parts[1], 16)))
functions.sort()
bases = [b for b, _ in functions]

sites = {}  # bctr address -> set(targets)
pat = re.compile(r"Switch case at ([0-9A-Fa-f]+) is trying to jump outside function: ([0-9A-Fa-f]+)")
for line in open(log_path, errors="replace"):
    m = pat.search(line)
    if m:
        sites.setdefault(int(m.group(1), 16), set()).add(int(m.group(2), 16))


def block_end(addr, limit=0x400):
    """Address just past the first return / unconditional branch at or after addr."""
    a = addr
    while a < addr + limit:
        w = word(a)
        if w == 0x4E800020 or w == 0x4E800420:   # blr / bctr
            return a + 4
        if (w >> 26) == 18 and (w & 3) == 0:     # b (not bl, not absolute)
            return a + 4
        a += 4
    return addr + limit


# Every function whose range contains a failing jump site and misses some of its targets.
overrides = {}
unfixable = 0
for site, targets in sites.items():
    # candidates: functions with base <= site
    hi = bisect.bisect_right(bases, site)
    for base, size in functions[max(0, hi - 64):hi]:
        if not (base <= site < base + size):
            continue
        outside = [t for t in targets if not (base <= t < base + size)]
        if not outside:
            continue

        ahead = [t for t in outside if t >= base + size]
        if len(ahead) != len(outside):
            unfixable += 1
            continue

        end = max(block_end(t) for t in ahead)
        new_size = end - base
        if new_size > size and new_size > overrides.get(base, 0):
            overrides[base] = new_size

# Merge with overrides from earlier iterations (never shrink).
if prev_path:
    for line in open(prev_path):
        m = re.search(r"address = (0x[0-9A-Fa-f]+), size = (0x[0-9A-Fa-f]+)", line)
        if m:
            a, sz = int(m.group(1), 16), int(m.group(2), 16)
            if sz > overrides.get(a, 0):
                overrides[a] = sz

with open(out_path, "w", newline="\n") as f:
    f.write("# Generated by fix_switch_functions.py - function extents implied by jump-table targets.\n")
    f.write("functions = [\n")
    for base in sorted(overrides):
        f.write("    { address = 0x%08X, size = 0x%X },\n" % (base, overrides[base]))
    f.write("]\n")

print("recompiler functions            : %d" % len(functions))
print("jump sites with outside targets : %d" % len(sites))
print("functions to extend             : %d" % len(overrides))
print("sites with targets before start : %d (not fixable by extending)" % unfixable)
for base in sorted(overrides)[:8]:
    old = next(s for b, s in functions if b == base)
    print("  0x%08X  0x%X -> 0x%X" % (base, old, overrides[base]))
