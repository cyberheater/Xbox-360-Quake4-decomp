# Generates q4_tag_hooks.toml and src/q4_tagscope.cpp: scans the executable image for every lwz/stw of the
# memory-tag scope global (lis rX,0x8308 ; lwz/stw rY,0x63EC(rX)). Paths at the top are the build machine's.
import struct,json,collections
d=open('/home/claude/q4_image.bin','rb').read()
B=0x82000000
sizes=json.load(open('/home/claude/guest_sizes.json'))
W=lambda a: struct.unpack('>I',d[a-B:a-B+4])[0]
sites=[];odd=collections.Counter();funcs=set()
for fs,sz in sizes.items():
  f=int(fs,16)
  for a in range(f,f+sz,4):
    w=W(a); op=w>>26; rt=(w>>21)&31; ra=(w>>16)&31; dd=w&0xffff
    if dd!=25580 or op not in (32,36,14,34,38,44,40): continue  # lwz stw addi lbz stb sth lhz
    if ra==0: continue
    # find lis ra,-31992 earlier in function (nearest def)
    ok=False
    for b in range(a-4,f-4,-4):
      x=W(b)
      if (x>>26)==15 and ((x>>21)&31)==ra and ((x>>16)&31)==0:
        ok = (x&0xffff)==0x8308; break
    if not ok: continue
    name={32:'lwz',36:'stw',14:'addi',34:'lbz',38:'stb',44:'sth',40:'lhz'}[op]
    if name not in('lwz','stw'): odd[name]+=1
    sites.append((a,name,rt,ra)); funcs.add(f)
print(len(sites),'sites in',len(funcs),'functions; odd',odd)
c=collections.Counter(s[1] for s in sites); print(c)
json.dump(sites,open('/home/claude/tagall.json','w'))
import json
s=json.load(open('/home/claude/tagall.json'))
sizes={int(k,16):v for k,v in json.load(open('/home/claude/guest_sizes.json')).items()}
starts=sorted(sizes)
import bisect
out=['# q4 - thread-private memory-tag scope for the renderer back-end thread (src/q4_tagscope.cpp).',
'# Generated by gen_tag.py: every lwz/stw of the tag scope pointer (0x830863EC) in the executable.',
'# On the back-end thread the hook does the load/store on a per-thread slot and skips the instruction;',
'# on every other thread it returns false and the original instruction runs.','']
regs=set()
for a,op,rt,ra in sorted(s):
  i=bisect.bisect_right(starts,a)-1; f=starts[i]
  assert a+4 < f+sizes[f], hex(a)
  nm=f"Q4Tag_{'L' if op=='lwz' else 'S'}_r{rt}"
  regs.add((op,rt))
  out+=['[[midasm_hook]]',f'address = 0x{a:08X}',f'name = "{nm}"',f'registers = ["r{rt}"]',f'jump_address_on_true = 0x{a+4:08X}','']
open('/home/claude/q4hle/q4_tag_hooks.toml','w').write('\n'.join(out))
c=['// q4 - thread-private memory-tag scope (hooks generated into q4_tag_hooks.toml by gen_tag.py).',
'//',
'// The game keeps the current memory tag scope in one global (0x830863EC): functions push a stack',
'// record {tag, previous} and set the global to it, and pop with global = global->previous. That',
'// assumes one thread. When the renderer back end runs on its own thread (q4hle, Q4_RB_THREAD), its',
'// pushes and pops would interleave with the game thread\'s and leave the global pointing at dead',
'// stack records. Every load and store of that global is hooked: on a thread that called',
'// q4tag::UsePrivateScope() it uses a per-thread slot instead; elsewhere the original runs.',
'',
'#include <rex/ppc/context.h>','#include <cstdint>','',
'namespace q4tag {','thread_local bool t_private = false;','thread_local uint32_t t_slot = 0;',
'void UsePrivateScope() { t_private = true; t_slot = 0; }','}  // namespace q4tag','']
for op,rt in sorted(regs):
  if op=='lwz':
    c.append(f'bool Q4Tag_L_r{rt}(PPCRegister& r{rt}) {{ if (!q4tag::t_private) return false; r{rt}.u64 = q4tag::t_slot; return true; }}')
  else:
    c.append(f'bool Q4Tag_S_r{rt}(PPCRegister& r{rt}) {{ if (!q4tag::t_private) return false; q4tag::t_slot = r{rt}.u32; return true; }}')
open('/home/claude/q4hle/src/q4_tagscope.cpp','w').write('\n'.join(c)+'\n')
print(len(s),len(regs))
